export type AvatarPath = (typeof AVATARS)[number];

export function isAvatarPath(value: string): value is AvatarPath {
  return (AVATARS as readonly string[]).includes(value);
}

export function defaultAvatarForAddress(address: string): AvatarPath {
  let hash = 0;
  for (let i = 0; i < address.length; i++) {
    hash = (hash * 31 + address.charCodeAt(i)) >>> 0;
  }
  return AVATARS[hash % AVATARS.length]!;
}
